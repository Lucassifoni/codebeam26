defmodule Bbparty.FontBundle do
  @max_id_bytes 46
  @static_prefix "/fonts/"

  @pins [
    %{
      family: "BB Emoji",
      source: "Boogy Brut Regular",
      ranges: "U+1F600-1F64F, U+1F900-1F9FF",
      why: "only Boogy Brut and its siblings draw these; every other face has none"
    },
    %{
      family: "BB Apple",
      source: "Brut Grotesque Medium",
      ranges: "U+F8FF",
      why: "every face draws this one; the installation wants this face's drawing"
    }
  ]

  @type font :: %{
          id: String.t(),
          family: String.t(),
          file: String.t(),
          source: String.t(),
          features: [String.t()]
        }

  @type problem ::
          {:malformed, term()}
          | {:empty_name, String.t()}
          | {:too_long, String.t(), pos_integer()}
          | {:duplicate, String.t(), pos_integer()}
          | {:bad_file, String.t(), term()}

  @spec max_id_bytes() :: pos_integer()
  def max_id_bytes, do: @max_id_bytes

  @spec fonts(map()) :: {:ok, [font()]} | {:error, [problem()]}
  def fonts(%{"fonts" => entries}) when is_list(entries) do
    {fonts, problems} =
      entries
      |> Enum.map(&font/1)
      |> Enum.split_with(&match?({:ok, _}, &1))

    fonts = Enum.map(fonts, fn {:ok, font} -> font end)
    problems = Enum.map(problems, fn {:error, problem} -> problem end) ++ duplicates(fonts)

    case problems do
      [] -> {:ok, Enum.sort_by(fonts, & &1.id)}
      _ -> {:error, problems}
    end
  end

  def fonts(export), do: {:error, [{:malformed, export}]}

  @spec export_problems(map()) :: [map()]
  def export_problems(%{"problems" => problems}) when is_list(problems), do: problems
  def export_problems(_export), do: []

  @spec file_name(String.t()) :: String.t()
  def file_name(export_path), do: Path.basename(export_path)

  @spec manifest_json([font()]) :: String.t()
  def manifest_json(fonts) do
    %{
      "comment" =>
        "Generated by `mix bbparty.fonts` from a bureaubrut export — do not edit. " <>
          "`id` is the name burnt on the NFC tags, `family` the CSS family, `features` " <>
          "every OpenType tag the face offers. Hand-kept faces live in fonts.system.json.",
      "fonts" => Enum.map(fonts, &manifest_entry/1)
    }
    |> Jason.encode_to_iodata!(pretty: true)
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  @spec pins() :: [%{family: String.t(), source: String.t(), ranges: String.t(), why: String.t()}]
  def pins, do: @pins

  @spec pinned_families() :: [String.t()]
  def pinned_families, do: Enum.map(@pins, & &1.family)

  @spec pin_sources() :: [String.t()]
  def pin_sources, do: Enum.map(@pins, & &1.source)

  @spec font_faces_css([font()]) :: String.t()
  def font_faces_css(fonts) do
    header =
      "/* Generated by `mix bbparty.fonts` — do not edit. One face per family: the\n" <>
        "   family is the font's id, which is the name burnt on the NFC tags. */\n"

    header <>
      "\n" <>
      Enum.map_join(@pins, "", &pin_face(&1, fonts)) <>
      Enum.map_join(fonts, "\n", &font_face/1)
  end

  @spec missing_pin_sources([font()]) :: [String.t()]
  def missing_pin_sources(fonts) do
    ids = MapSet.new(fonts, & &1.id)
    Enum.reject(pin_sources(), &MapSet.member?(ids, &1))
  end

  defp pin_face(pin, fonts) do
    case Enum.find(fonts, &(&1.id == pin.source)) do
      nil ->
        ""

      font ->
        """
        /* Pinned to #{pin.source}, whatever the panel selects —
           #{pin.why}.
           Restricted by unicode-range, so it claims nothing else and the
           selected font still draws every other character. */
        @font-face {
          font-family: "#{css_string(pin.family)}";
          src: url("#{@static_prefix}#{font.file}") format("woff2");
          unicode-range: #{pin.ranges};
          font-display: block;
        }
        """ <> "\n"
    end
  end

  @spec report([font()], [String.t()]) :: %{
          frequencies: [{String.t(), pos_integer()}],
          unknown: [String.t()],
          fonts: non_neg_integer()
        }
  def report(fonts, known) do
    frequencies =
      fonts
      |> Enum.flat_map(& &1.features)
      |> Enum.frequencies()
      |> Enum.sort_by(fn {tag, count} -> {-count, tag} end)

    %{
      fonts: length(fonts),
      frequencies: frequencies,
      unknown: frequencies |> Enum.map(&elem(&1, 0)) |> Enum.reject(&(&1 in known))
    }
  end

  @spec compare_names([font()], [String.t()]) :: %{
          burnt_without_font: [String.t()],
          fonts_without_tag: [String.t()]
        }
  def compare_names(fonts, burnt) do
    ids = MapSet.new(fonts, & &1.id)
    burnt = burnt |> Enum.reject(&(&1 == "")) |> MapSet.new()

    %{
      burnt_without_font: burnt |> MapSet.difference(ids) |> Enum.sort(),
      fonts_without_tag: ids |> MapSet.difference(burnt) |> Enum.sort()
    }
  end

  @spec format_problems([problem()]) :: String.t()
  def format_problems(problems), do: Enum.map_join(problems, "\n", &("  " <> describe(&1)))

  defp font(%{"name" => name, "file" => file, "features" => features} = entry)
       when is_binary(name) and is_binary(file) and is_list(features) do
    with :ok <- check_name(name),
         :ok <- check_file(name, file),
         :ok <- check_features(entry, features) do
      {:ok,
       %{
         id: name,
         family: name,
         file: file_name(file),
         source: file,
         features: features |> Enum.uniq() |> Enum.sort()
       }}
    end
  end

  defp font(entry), do: {:error, {:malformed, entry}}

  defp check_name(""), do: {:error, {:empty_name, ""}}

  defp check_name(name) do
    case byte_size(name) do
      size when size > @max_id_bytes -> {:error, {:too_long, name, size}}
      _size -> :ok
    end
  end

  defp check_file(name, file) do
    base = file_name(file)

    case Regex.match?(~r/\A[A-Za-z0-9._-]+\.woff2\z/, base) do
      true -> :ok
      false -> {:error, {:bad_file, name, file}}
    end
  end

  defp check_features(entry, features) do
    case Enum.all?(features, &is_binary/1) do
      true -> :ok
      false -> {:error, {:malformed, entry}}
    end
  end

  defp duplicates(fonts) do
    fonts
    |> Enum.frequencies_by(& &1.id)
    |> Enum.filter(fn {_id, count} -> count > 1 end)
    |> Enum.sort()
    |> Enum.map(fn {id, count} -> {:duplicate, id, count} end)
  end

  defp manifest_entry(font) do
    %{"id" => font.id, "family" => font.family, "file" => font.file, "features" => font.features}
  end

  defp font_face(font) do
    """
    @font-face {
      font-family: "#{css_string(font.family)}";
      src: url("#{@static_prefix}#{font.file}") format("woff2");
      font-display: block;
    }
    """
  end

  defp css_string(value),
    do: value |> String.replace("\\", "\\\\") |> String.replace("\"", "\\\"")

  defp describe({:malformed, entry}), do: "malformed entry: #{inspect(entry)}"
  defp describe({:empty_name, _}), do: "a font has an empty name"

  defp describe({:too_long, name, size}),
    do: "#{inspect(name)} is #{size} bytes; a tag holds #{@max_id_bytes}"

  defp describe({:duplicate, name, count}), do: "#{inspect(name)} names #{count} fonts"

  defp describe({:bad_file, name, file}),
    do: "#{inspect(name)} has an unusable file #{inspect(file)}"
end
